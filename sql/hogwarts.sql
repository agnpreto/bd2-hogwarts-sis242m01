-- ---------- Nivel 2: JOINs ----------

-- 6.7 Alunos que possuem casa (INNER JOIN)
SELECT a.nome AS aluno, c.nome_casa AS casa
FROM aluno a
INNER JOIN casa c ON c.id_casa = a.id_casa
ORDER BY c.nome_casa, a.nome;

-- Quantos alunos e por que: 12. Teddy Lupin ainda nao possui casa e, por
