-- 6.8 Todos os alunos, inclusive quem nao tem casa (LEFT JOIN)
SELECT
    a.nome AS aluno,
    COALESCE(c.nome_casa, 'Aguardando o Chapéu Seletor') AS casa
FROM aluno a
LEFT JOIN casa c ON c.id_casa = a.id_casa
ORDER BY a.nome;

-- 6.9 Professores que nao ministram disciplina (RIGHT JOIN)
SELECT p.nome AS professor
FROM disciplina d
RIGHT JOIN professor p ON p.id_prof = d.id_prof
WHERE d.id_disc IS NULL
ORDER BY p.nome;

-- 6.10 Boletim da Grifinória (5 tabelas; professor pode estar ausente)
SELECT
    a.nome AS aluno,
    d.nome_disc AS disciplina,
    COALESCE(p.nome, 'Sem professor') AS professor,
    m.nota,
    m.situacao
FROM aluno a
INNER JOIN casa c ON c.id_casa = a.id_casa
INNER JOIN matricula m ON m.id_aluno = a.id_aluno
INNER JOIN disciplina d ON d.id_disc = m.id_disc
LEFT JOIN professor p ON p.id_prof = d.id_prof
WHERE c.nome_casa = 'Grifinória'
ORDER BY a.nome, d.nome_disc;

-- 6.11 Extrato do Beco Diagonal (3 tabelas)
SELECT
    c.id_compra AS numero_compra,
    a.nome AS aluno,
    p.nome_produto AS produto,
    p.loja,
    c.quantidade,
    c.valor_total,
    c.data_compra
FROM compra c
INNER JOIN aluno a ON a.id_aluno = c.id_aluno
INNER JOIN produto p ON p.id_produto = c.id_produto
ORDER BY c.data_compra, c.id_compra;

-- ---------- Nivel 3: agrupamento e agregacao ----------

-- 6.12 Desempenho por disciplina
SELECT
    d.nome_disc AS disciplina,
    COUNT(m.id_aluno) AS quantidade_alunos,
    ROUND(AVG(m.nota), 2) AS media,
    MAX(m.nota) AS maior_nota,
    MIN(m.nota) AS menor_nota
FROM disciplina d
INNER JOIN matricula m ON m.id_disc = d.id_disc
GROUP BY d.id_disc, d.nome_disc
HAVING AVG(m.nota) >= 7
ORDER BY media DESC, d.nome_disc;

-- 6.13 Livro-razao da Taca das Casas
SELECT
    c.nome_casa AS casa,
    COUNT(rp.id_registro) AS quantidade_registros,
    COALESCE(SUM(CASE WHEN rp.pontos > 0 THEN rp.pontos ELSE 0 END), 0)
        AS pontos_ganhos,
    COALESCE(SUM(CASE WHEN rp.pontos < 0 THEN ABS(rp.pontos) ELSE 0 END), 0)
        AS pontos_perdidos,
    c.pontos AS saldo
FROM casa c
LEFT JOIN aluno a ON a.id_casa = c.id_casa
LEFT JOIN registro_pontos rp ON rp.id_aluno = a.id_aluno
GROUP BY c.id_casa, c.nome_casa, c.pontos
ORDER BY c.nome_casa;

-- 6.14 Faturamento por loja
SELECT
    p.loja,
    COUNT(c.id_compra) AS quantidade_compras,
    SUM(c.valor_total) AS faturamento
FROM compra c
INNER JOIN produto p ON p.id_produto = c.id_produto
GROUP BY p.loja
HAVING SUM(c.valor_total) > 20
ORDER BY faturamento DESC;

-- 6.15 Pontos por mes
SELECT
    EXTRACT(MONTH FROM data_registro)::INT AS mes,
    COUNT(*) AS quantidade_registros,
    SUM(pontos) AS total_pontos
FROM registro_pontos
GROUP BY EXTRACT(MONTH FROM data_registro)
ORDER BY EXTRACT(MONTH FROM data_registro);

-- 6.16 Professores mais ativos
SELECT
    p.nome AS professor,
    COUNT(rp.id_registro) AS quantidade_registros,
    SUM(rp.pontos) AS total_concedido
FROM professor p
INNER JOIN registro_pontos rp ON rp.id_prof = p.id_prof
GROUP BY p.id_prof, p.nome
HAVING COUNT(rp.id_registro) >= 2
ORDER BY total_concedido DESC, p.nome;

-- ---------- Nivel 4: subconsultas ----------

-- 6.17 Clientes da Dedosdemel (IN, sem JOIN)
SELECT a.nome AS aluno
FROM aluno a
WHERE a.id_aluno IN (
    SELECT c.id_aluno
    FROM compra c
    WHERE c.id_produto IN (
        SELECT p.id_produto
        FROM produto p
        WHERE p.loja = 'Dedosdemel'
    )
)
ORDER BY a.nome;

-- 6.18 Produtos nunca comprados (NOT IN)
SELECT p.nome_produto, p.estoque
FROM produto p
WHERE p.id_produto NOT IN (
    SELECT c.id_produto
    FROM compra c
)
ORDER BY p.nome_produto;

-- 6.19 Alunos com saldo acima da media (subconsulta escalar)
SELECT nome, saldo_galeoes
FROM aluno
WHERE saldo_galeoes > (
    SELECT AVG(saldo_galeoes)
    FROM aluno
)
ORDER BY saldo_galeoes DESC;

-- 6.20 Professores que ganham mais do que todos os nao diretores (ALL)
SELECT nome, salario
FROM professor
WHERE salario > ALL (
    SELECT salario
    FROM professor
    WHERE id_casa IS NULL
)
ORDER BY salario DESC;

-- 6.21 Alunos nao sonserinos com saldo maior que o de algum sonserino (ANY)
SELECT a.nome, a.saldo_galeoes
FROM aluno a
WHERE (a.id_casa IS NULL OR a.id_casa <> (
          SELECT id_casa FROM casa WHERE nome_casa = 'Sonserina'
      ))
  AND a.saldo_galeoes > ANY (
      SELECT saldo_galeoes
      FROM aluno
      WHERE id_casa = (SELECT id_casa FROM casa WHERE nome_casa = 'Sonserina')
  )
ORDER BY a.saldo_galeoes DESC;

-- > ANY equivale a: ser maior que pelo menos um valor retornado pela
-- subconsulta (neste caso, maior que o menor saldo entre os sonserinos).

-- 6.22 Casas com pelo menos um aluno que tirou nota 10 (EXISTS)
SELECT c.nome_casa
FROM casa c
WHERE EXISTS (
    SELECT 1
    FROM aluno a
    INNER JOIN matricula m ON m.id_aluno = a.id_aluno
    WHERE a.id_casa = c.id_casa
      AND m.nota = 10
)
ORDER BY c.nome_casa;

-- 6.23 Alunos que nunca fizeram compra (NOT EXISTS)
SELECT a.nome
FROM aluno a
WHERE NOT EXISTS (
    SELECT 1
    FROM compra c
    WHERE c.id_aluno = a.id_aluno
)
ORDER BY a.nome;

-- 6.24 Media das medias por casa (subconsulta no FROM)
SELECT
    c.nome_casa AS casa,
    ROUND(AVG(medias.media_aluno), 2) AS media_das_medias
FROM (
    SELECT
        a.id_aluno,
        a.id_casa,
        AVG(m.nota) AS media_aluno
    FROM aluno a
    INNER JOIN matricula m ON m.id_aluno = a.id_aluno
    GROUP BY a.id_aluno, a.id_casa
) AS medias
INNER JOIN casa c ON c.id_casa = medias.id_casa
GROUP BY c.id_casa, c.nome_casa
ORDER BY media_das_medias DESC;

