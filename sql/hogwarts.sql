-- Questao 20 - trg_pontos_casa
CREATE OR REPLACE FUNCTION fn_pontos_casa()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    UPDATE casa
    SET pontos = pontos + NEW.pontos
    WHERE id_casa = (SELECT id_casa FROM aluno WHERE id_aluno = NEW.id_aluno);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_pontos_casa
AFTER INSERT ON registro_pontos
FOR EACH ROW EXECUTE FUNCTION fn_pontos_casa();

-- Questao 21 - trg_valida_compra
CREATE OR REPLACE FUNCTION fn_valida_compra()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_estoque INT;
    v_preco DECIMAL(10,2);
    v_saldo DECIMAL(10,2);
BEGIN
    SELECT estoque, preco INTO v_estoque, v_preco
    FROM produto WHERE id_produto = NEW.id_produto;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Produto inexistente';
    END IF;
    IF v_estoque < NEW.quantidade THEN
        RAISE EXCEPTION 'Estoque insuficiente no Beco Diagonal';
    END IF;

    SELECT saldo_galeoes INTO v_saldo
    FROM aluno WHERE id_aluno = NEW.id_aluno;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Aluno inexistente';
    END IF;
    IF v_saldo < (v_preco * NEW.quantidade) THEN
        RAISE EXCEPTION 'Galeoes insuficientes no cofre do aluno';
    END IF;

    NEW.valor_total := v_preco * NEW.quantidade;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_valida_compra
BEFORE INSERT ON compra
FOR EACH ROW EXECUTE FUNCTION fn_valida_compra();

-- Questao 22 - trg_baixa_compra
CREATE OR REPLACE FUNCTION fn_baixa_compra()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    UPDATE produto SET estoque = estoque - NEW.quantidade
    WHERE id_produto = NEW.id_produto;
    UPDATE aluno SET saldo_galeoes = saldo_galeoes - NEW.valor_total
    WHERE id_aluno = NEW.id_aluno;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_baixa_compra
AFTER INSERT ON compra
FOR EACH ROW EXECUTE FUNCTION fn_baixa_compra();

-- Questao 23 - trg_situacao_nota
CREATE OR REPLACE FUNCTION fn_situacao_nota()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.nota IS DISTINCT FROM NEW.nota THEN
        IF NEW.nota >= 6 THEN
            NEW.situacao := 'Aprovado';
        ELSE
            NEW.situacao := 'Reprovado';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_situacao_nota
BEFORE UPDATE ON matricula
FOR EACH ROW EXECUTE FUNCTION fn_situacao_nota();

-- Questao 24 - trg_audita_salario
CREATE OR REPLACE FUNCTION fn_audita_salario()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF OLD.salario IS DISTINCT FROM NEW.salario THEN
        INSERT INTO log_auditoria (tabela, operacao, descricao)
        VALUES (
            'professor',
            'UPDATE',
            OLD.nome || ': salario de ' || OLD.salario::text || ' para ' || NEW.salario::text
        );
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_audita_salario
AFTER UPDATE ON professor
FOR EACH ROW EXECUTE FUNCTION fn_audita_salario();

-- Pergunta para pensar: por que validacao BEFORE e baixa AFTER?
-- Resposta: a validacao acontece antes para impedir que uma compra invalida
-- seja gravada. A baixa acontece depois porque depende de a compra ter sido
-- inserida com sucesso. Assim, estoque e saldo so sao alterados para compras
-- validas. Como as tabelas usam InnoDB, a compra e as alteracoes do trigger
-- participam da mesma transacao.

